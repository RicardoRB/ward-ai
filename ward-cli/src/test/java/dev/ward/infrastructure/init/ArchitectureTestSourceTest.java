package dev.ward.infrastructure.init;

import static org.assertj.core.api.Assertions.assertThat;

import dev.ward.domain.init.QualityPreset;
import org.junit.jupiter.api.Test;

/** The generated ArchUnit test when the ward engine owns the layers and the cycles. */
class ArchitectureTestSourceTest {

  @Test
  void withoutALayerRuleItImportsOnlyWhatItUses() {
    final String source =
        ArchitectureTestSource.render(
            "shop", null, new QualityPreset.ArchitectureExtras(false, true, true));

    assertThat(source)
        .doesNotContain("noClasses", "beFreeOfCycles", "slices()")
        .contains("import com.tngtech.archunit.library.GeneralCodingRules;\n\n// Generated by Ward")
        .doesNotContain("package shop;\n\n\n");
  }

  @Test
  void withALayerRuleItKeepsTheStaticImportAndItsBlankLine() {
    final String source =
        ArchitectureTestSource.render(
            "shop", "hexagonal", new QualityPreset.ArchitectureExtras(false, true, true));

    assertThat(source)
        .startsWith(
            "package shop;\n\nimport static com.tngtech.archunit.lang.syntax.ArchRuleDefinition.noClasses;\n\n");
  }
}
