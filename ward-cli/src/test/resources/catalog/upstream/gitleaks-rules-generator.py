#!/usr/bin/env python3
"""One-off generator of Ward's secret rules from the pinned Gitleaks default configuration.

Command (the output is committed; Ward never reads a Gitleaks file at run time):

    curl -fsSL https://raw.githubusercontent.com/gitleaks/gitleaks/v8.30.1/config/gitleaks.toml \
        -o /tmp/gitleaks.toml
    python3 -I ward-cli/src/test/resources/catalog/upstream/gitleaks-rules-generator.py \
        /tmp/gitleaks.toml ward-cli/src/main/resources/rules/secrets

It writes secrets.toml (one rule per Gitleaks rule) and secrets-allowlist.toml (the global
allowlist). The rule data is from Gitleaks, MIT licence, Copyright (c) 2019 Zachary Rice; see NOTICE.

Translations from Go (RE2) to Java regex syntax: the POSIX class [[:alnum:]] becomes \\p{Alnum},
a named group (?P<name> becomes a plain group (Java names cannot hold '_', and no rule reads a name),
and a '{' that is not a quantifier becomes \\{.
"""
import re
import sys
import tomllib
from pathlib import Path

MULTILINE_RULES = {
    "curl-auth-header",
    "curl-auth-user",
    "jwt-base64",
    "kubernetes-secret-yaml",
    "private-key",
}
QUANTIFIER = re.compile(r"\{\d+(?:,\d*)?\}")


def java_regex(regex: str) -> str:
    regex = regex.replace("[[:alnum:]]", r"\p{Alnum}")
    regex = re.sub(r"\(\?P<\w+>", "(", regex)
    out, i, in_class = [], 0, False
    while i < len(regex):
        c = regex[i]
        if c == "\\":
            end = i + 2
            if regex[i + 1] in "pPx" and regex[end : end + 1] == "{":
                end = regex.index("}", end) + 1
            out.append(regex[i:end])
            i = end
            continue
        if c == "[" and not in_class:
            in_class = True
        elif c == "]" and in_class:
            in_class = False
        elif c == "{" and not in_class and not (QUANTIFIER.match(regex, i) and i > 0):
            c = "\\{"
        out.append(c)
        i += 1
    return "".join(out)


def string(value: str) -> str:
    """A TOML string that is safe inside the ''' body of a rule."""
    if "'" not in value and "\n" not in value:
        return "'" + value + "'"
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return '"' + escaped + '"'


def array(values) -> str:
    return "[" + ", ".join(string(v) for v in values) + "]"


def allowlist(entry: dict) -> str:
    parts = []
    for key in ("paths", "regexes"):
        if key in entry:
            values = [java_regex(v) for v in entry[key]]
            parts.append(f"{key} = {array(values)}")
    if "stopwords" in entry:
        parts.append(f"stopwords = {array(entry['stopwords'])}")
    if "regexTarget" in entry:
        parts.append(f'regex-target = "{entry["regexTarget"]}"')
    if entry.get("condition", "OR").upper() == "AND":
        parts.append('condition = "and"')
    return "{ " + ", ".join(parts) + " }"


def rule(entry: dict) -> str:
    rid = entry["id"]
    message = f"Potential secret detected by rule {rid}. Remove it and rotate the credential."
    body = ['check = "secret-scan"']
    body.append(f"description = {string(entry['description'])}")
    body.append(f'message = "{message}"')
    if "regex" in entry:
        body.append(f"regex = {string(java_regex(entry['regex']))}")
    if "path" in entry:
        body.append(f"path = {string(java_regex(entry['path']))}")
    if entry.get("keywords"):
        body.append(f"keywords = {array(entry['keywords'])}")
    if "entropy" in entry:
        body.append(f"entropy = {float(entry['entropy'])}")
    if "secretGroup" in entry:
        body.append(f"secret-group = {entry['secretGroup']}")
    if rid in MULTILINE_RULES:
        body.append('span = "text"')
    if entry.get("allowlists"):
        body.append("allowlists = [" + ", ".join(allowlist(a) for a in entry["allowlists"]) + "]")
    body.append('allowlist = "default"')
    text = "\n".join(body)
    assert "'''" not in text, rid
    return (
        "[[rules]]\n"
        f'id = "ward:secrets/{rid}"\n'
        'scope = "text"\n'
        'capability = "TEXT"\n'
        'severity = "error"\n'
        'category = "secrets"\n'
        'options.entropy = { type = "number", min = 0 }\n'
        "body = '''\n" + text + "\n'''\n"
    )


def main() -> None:
    source, target = Path(sys.argv[1]), Path(sys.argv[2])
    config = tomllib.loads(source.read_text(encoding="utf-8"))
    header = (
        "# Generated by catalog/upstream/gitleaks-rules-generator.py from the Gitleaks 8.30.1\n"
        "# default configuration (MIT licence, see NOTICE). Do not edit by hand.\n\n"
    )
    rules = sorted(config["rules"], key=lambda r: r["id"])
    (target / "secrets.toml").write_text(
        header + "\n".join(rule(r) for r in rules), encoding="utf-8"
    )
    glob = config["allowlist"]
    (target / "secrets-allowlist.toml").write_text(
        header
        + f"paths = {array([java_regex(v) for v in glob['paths']])}\n"
        + f"regexes = {array([java_regex(v) for v in glob['regexes']])}\n"
        + f"stopwords = {array(glob['stopwords'])}\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
