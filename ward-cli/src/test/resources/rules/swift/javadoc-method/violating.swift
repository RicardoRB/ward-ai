/**
 * Adds two numbers.
 * - Parameter a: first number.
 * - Parameter b: second number.
 */
func add(a: Int, b: Int) -> Int { a + b }

/// Converts the value.
///
/// - Parameters:
///   - value: The value to convert
/// - Returns: The converted value.
func convert(value: Double, clamped: Bool) -> Double { value }
