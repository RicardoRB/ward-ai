// Compares Ward's structural rules with ESLint core on the same fixtures, and prints the report.
//
// Usage (from ward-lang-node/parity, after `npm ci`):
//   node compare.mjs <ward.json> <fixture-root> > ../PARITY.md
//
// <ward.json> comes from NodeParityDumpTest:
//   ./mvnw -pl ward-lang-node test -Dtest=NodeParityDumpTest -Dward.parity.out=<ward.json>
//
// Every ESLint rule runs with its core defaults. The disagreements that are known and understood
// are listed in known-differences.json with their reasons; any other disagreement is reported as
// unexplained, so a new difference cannot pass silently.

import { readFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { ESLint } from "eslint";
import tsParser from "@typescript-eslint/parser";

// Ward rule metric -> ESLint core rule, with the default options of each.
const CORE = {
  "function-length": "max-lines-per-function",
  "parameter-count": "max-params",
  complexity: "complexity",
  "file-length": "max-lines",
  naming: "camelcase",
  "nesting-depth": "max-depth",
};

const DIALECTS = [
  { glob: "ts/*.ts", language: "typescript", config: { languageOptions: { parser: tsParser, sourceType: "module" } } },
  { glob: "js-esm/*.mjs", language: "javascript", config: { languageOptions: { sourceType: "module" } } },
  { glob: "js-cjs/*.cjs", language: "javascript", config: { languageOptions: { sourceType: "commonjs" } } },
];

const [wardPath, fixtureArg] = process.argv.slice(2);
if (!wardPath || !fixtureArg) {
  console.error("usage: node compare.mjs <ward.json> <fixture-root>");
  process.exit(2);
}
const fixtureRoot = resolve(fixtureArg);
const ward = JSON.parse(readFileSync(wardPath, "utf8"));
const known = JSON.parse(readFileSync(new URL("./known-differences.json", import.meta.url), "utf8"));

function wardLines(rule, file) {
  const entry = ward.find((e) => e.rule === rule && e.file === file);
  if (!entry) throw new Error(`no Ward result for ${rule} on ${file}`);
  return entry.lines;
}

async function eslintLines(metric, dialect) {
  const eslint = new ESLint({
    cwd: fixtureRoot,
    overrideConfigFile: true,
    overrideConfig: [
      {
        files: [dialect.glob],
        ...dialect.config,
        rules: { [CORE[metric]]: "error" },
      },
    ],
  });
  const results = await eslint.lintFiles([dialect.glob]);
  const byFile = new Map();
  for (const result of results) {
    const file = relative(fixtureRoot, result.filePath);
    byFile.set(
      file,
      result.messages.filter((m) => m.ruleId === CORE[metric]).map((m) => m.line),
    );
  }
  return byFile;
}

function sameLines(a, b) {
  return a.length === b.length && a.every((line, i) => line === b[i]);
}

const eslintVersion = JSON.parse(readFileSync(new URL("./node_modules/eslint/package.json", import.meta.url), "utf8")).version;
const rows = [];
const unexplained = [];

for (const [metric, core] of Object.entries(CORE)) {
  for (const dialect of DIALECTS) {
    const esl = await eslintLines(metric, dialect);
    const own = new RegExp(`^[^/]+/${metric}-(violating|passing)\\.`);
    for (const [file, eslintResult] of [...esl.entries()].filter(([f]) => own.test(f)).sort()) {
      const wardRule = `ward:${dialect.language}/${metric}`;
      const wardResult = wardLines(wardRule, file);
      const agree = sameLines(wardResult, eslintResult);
      const key = `${metric}:${file}`;
      const reason = known[key];
      rows.push({ metric, core, file, wardRule, wardResult, eslintResult, agree, reason });
      if (!agree && !reason) unexplained.push(key);
    }
  }
}

const lines = [];
lines.push("# Structural rules: parity with ESLint core");
lines.push("");
lines.push(
  `Generated by \`ward-lang-node/parity/compare.mjs\` against ESLint ${eslintVersion} with core rules at their defaults. ` +
    "Each row is one fixture. A fixture agrees when both tools report the same lines.",
);
lines.push("");
lines.push("## Gaps stated up front");
lines.push("");
lines.push(
  "- `naming` covers only the ESLint core `camelcase` behaviour. Class and type casing has no core ESLint rule and is not checked.",
);
lines.push(
  "- Metrics count the tree of the frontend. A unit with a syntax error gives a partial tree, so results inside that unit are best effort.",
);
lines.push("- Rules run per function where ESLint runs per function; top-level code is measured by `file-length` only.");
lines.push("");
lines.push("## Results");
lines.push("");
lines.push(`Agreeing fixtures: ${rows.filter((r) => r.agree).length} of ${rows.length}.`);
lines.push("");
lines.push("| Rule | ESLint core | Fixture | Ward lines | ESLint lines | Agree | Reason |");
lines.push("|---|---|---|---|---|---|---|");
for (const r of rows) {
  lines.push(
    `| \`${r.wardRule}\` | \`${r.core}\` | \`${r.file}\` | ${JSON.stringify(r.wardResult)} | ${JSON.stringify(r.eslintResult)} | ${r.agree ? "yes" : "no"} | ${r.reason ?? ""} |`,
  );
}
lines.push("");
console.log(lines.join("\n"));

if (unexplained.length > 0) {
  console.error(`unexplained differences: ${unexplained.join(", ")}`);
  process.exit(1);
}
